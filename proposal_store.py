"""SQLite ledger of proposals, reviewer decisions and applied operations.

A proposal is identified by its fingerprint: a hash of what it would change
(kind, subject, operations with their target values), not of when or how it
was found. The same situation found on tomorrow's run gets the same
fingerprint, so a proposal that was already rejected or applied is never put
back in front of the reviewer. A genuinely different change gets a new one.

Proposal lifecycle:
    pending -> approved -> applying -> applied
                                    -> failed     (retryable; resumes from the operations ledger)
                                    -> stale      (CRM changed since review; nothing written)
    pending -> rejected
    pending -> superseded (no longer generated by the latest run, e.g. fixed by hand)
"""
from __future__ import annotations

import hashlib
import json
import sqlite3
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from rules import Proposal, ReconciliationPlan

DEFAULT_DB_PATH = Path("data/entitysync.db")
DECIDED = ("approved", "applying", "applied", "failed", "stale", "rejected")

SCHEMA = """
CREATE TABLE IF NOT EXISTS runs (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    started_at TEXT NOT NULL,
    summary TEXT
);
CREATE TABLE IF NOT EXISTS proposals (
    fingerprint TEXT PRIMARY KEY,
    kind TEXT NOT NULL,
    title TEXT NOT NULL,
    subject TEXT NOT NULL,
    confidence TEXT NOT NULL,
    payload TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    first_run_id INTEGER NOT NULL,
    last_seen_run_id INTEGER NOT NULL,
    decided_at TEXT,
    decision_reason TEXT,
    result TEXT
);
CREATE TABLE IF NOT EXISTS operations (
    op_key TEXT PRIMARY KEY,
    fingerprint TEXT NOT NULL REFERENCES proposals(fingerprint),
    step INTEGER NOT NULL,
    account_id TEXT,
    status TEXT NOT NULL,
    response TEXT,
    updated_at TEXT NOT NULL
);
"""


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def fingerprint(proposal: Proposal) -> str:
    """Stable identity of a proposed change. Notes are descriptive, so they are left out."""
    ops = [
        {"op": op.op, "account_id": op.account_id, "fields": {k: v for k, v in sorted(op.fields.items()) if k != "note"}}
        for op in proposal.operations
    ]
    canonical = json.dumps({"kind": proposal.kind, "subject": proposal.subject, "operations": ops}, sort_keys=True)
    return hashlib.sha256(canonical.encode()).hexdigest()[:20]


def op_key(fp: str, step: int) -> str:
    """Idempotency key for one operation of one proposal. Same proposal + step -> same key on every retry."""
    return hashlib.sha256(f"{fp}:{step}".encode()).hexdigest()[:16]


class ProposalStore:
    def __init__(self, path: Path | str = DEFAULT_DB_PATH):
        if str(path) != ":memory:":
            Path(path).parent.mkdir(parents=True, exist_ok=True)
        self.db = sqlite3.connect(str(path))
        self.db.row_factory = sqlite3.Row
        self.db.executescript(SCHEMA)

    # ---- pipeline side -----------------------------------------------------

    def save_plan(self, plan: ReconciliationPlan, accounts: list[dict]) -> dict[str, int]:
        """Record one run's proposals. Returns counts of new / already-known / superseded proposals."""
        by_id = {a["account_id"]: a for a in accounts}
        with self.db:
            run_id = self.db.execute("INSERT INTO runs (started_at) VALUES (?)", (now(),)).lastrowid
            counts = {"new": 0, "pending_refreshed": 0, "already_decided": 0, "superseded": 0}
            seen = set()
            for p in plan.proposals:
                fp = fingerprint(p)
                seen.add(fp)
                payload = json.dumps(_payload(p, by_id))
                row = self.db.execute("SELECT status FROM proposals WHERE fingerprint = ?", (fp,)).fetchone()
                if row is None:
                    self.db.execute(
                        "INSERT INTO proposals (fingerprint, kind, title, subject, confidence, payload, first_run_id, last_seen_run_id)"
                        " VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                        (fp, p.kind, p.title, p.subject, p.confidence, payload, run_id, run_id))
                    counts["new"] += 1
                elif row["status"] in ("pending", "superseded"):
                    # Still relevant and undecided: refresh evidence and snapshots to the latest run.
                    self.db.execute(
                        "UPDATE proposals SET status = 'pending', title = ?, confidence = ?, payload = ?, last_seen_run_id = ?"
                        " WHERE fingerprint = ?", (p.title, p.confidence, payload, run_id, fp))
                    counts["pending_refreshed"] += 1
                else:
                    self.db.execute("UPDATE proposals SET last_seen_run_id = ? WHERE fingerprint = ?", (run_id, fp))
                    counts["already_decided"] += 1
            stale_pending = [r["fingerprint"] for r in self.db.execute("SELECT fingerprint FROM proposals WHERE status = 'pending'")
                             if r["fingerprint"] not in seen]
            for fp in stale_pending:
                self.set_status(fp, "superseded", result={"reason": "not generated by the latest run"})
            counts["superseded"] = len(stale_pending)
            self.db.execute("UPDATE runs SET summary = ? WHERE id = ?", (json.dumps(counts), run_id))
        return counts

    # ---- reviewer side -----------------------------------------------------

    def list(self, status: str | None = None) -> list[dict[str, Any]]:
        sql, args = "SELECT * FROM proposals", ()
        if status:
            sql, args = sql + " WHERE status = ?", (status,)
        rows = self.db.execute(sql + " ORDER BY kind, title", args).fetchall()
        return [self._row(r) for r in rows]

    def get(self, fp: str) -> dict[str, Any]:
        row = self.db.execute("SELECT * FROM proposals WHERE fingerprint = ?", (fp,)).fetchone()
        if row is None:
            raise KeyError(fp)
        return self._row(row)

    def decide(self, fp: str, decision: str, reason: str = "") -> None:
        if decision not in ("approved", "rejected"):
            raise ValueError(decision)
        current = self.get(fp)["status"]
        if current != "pending":
            raise ValueError(f"proposal {fp} is {current}; only pending proposals can be decided")
        with self.db:
            self.db.execute("UPDATE proposals SET status = ?, decided_at = ?, decision_reason = ? WHERE fingerprint = ?",
                            (decision, now(), reason, fp))

    def set_status(self, fp: str, status: str, result: dict | None = None) -> None:
        with self.db:
            self.db.execute("UPDATE proposals SET status = ?, result = ? WHERE fingerprint = ?",
                            (status, json.dumps(result) if result is not None else None, fp))

    # ---- operations ledger (used by the applier) ---------------------------

    def get_operation(self, key: str) -> dict | None:
        row = self.db.execute("SELECT * FROM operations WHERE op_key = ?", (key,)).fetchone()
        return dict(row) if row else None

    def record_operation(self, key: str, fp: str, step: int, status: str, account_id: str | None = None,
                         response: Any = None) -> None:
        with self.db:
            self.db.execute(
                "INSERT INTO operations (op_key, fingerprint, step, account_id, status, response, updated_at)"
                " VALUES (?, ?, ?, ?, ?, ?, ?)"
                " ON CONFLICT(op_key) DO UPDATE SET account_id = COALESCE(excluded.account_id, account_id),"
                " status = excluded.status, response = excluded.response, updated_at = excluded.updated_at",
                (key, fp, step, account_id, status, json.dumps(response) if response is not None else None, now()))

    def _row(self, row: sqlite3.Row) -> dict[str, Any]:
        out = dict(row)
        out["payload"] = json.loads(out["payload"])
        out["result"] = json.loads(out["result"]) if out["result"] else None
        return out


def _payload(p: Proposal, accounts_by_id: dict[str, dict]) -> dict:
    """Everything the reviewer and the applier need, including snapshots of every account the proposal touches."""
    touched = {op.account_id for op in p.operations if op.account_id}
    return {
        "operations": [asdict(op) for op in p.operations],
        "before": p.before,
        "after": p.after,
        "evidence": p.evidence,
        "flags": p.flags,
        "location": asdict(p.location) if p.location else None,
        "snapshots": {aid: accounts_by_id[aid] for aid in sorted(touched) if aid in accounts_by_id},
    }
